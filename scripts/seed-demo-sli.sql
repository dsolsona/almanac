-- Local development fixture. Run in one transaction with the derived-data marker.
SET LOCAL TIME ZONE 'UTC';
SET LOCAL statement_timeout = '30s';
SET LOCAL lock_timeout = '2s';

SELECT s.id AS fixture_id, m.revision AS fixture_revision,
       m.effective_from AS fixture_valid_from,
       d.polling_interval_seconds AS fixture_cadence,
       d.settling_delay_seconds AS fixture_delay
FROM public.almanac_slis s
JOIN public.almanac_sli_measurements m
  ON m.sli_id = s.id AND m.revision = s.measurement_revision
JOIN public.almanac_datasources d ON d.id = m.datasource_id
WHERE s.name = :'sli'
  AND m.measurement_kind = 'event_counts'
  AND m.component_mode = 'interval_count'
  AND m.good_query = 'vector(99)' AND m.total_query = 'vector(100)'
  AND d.endpoint = 'http://victoriametrics:8428'
FOR NO KEY UPDATE OF m
FOR UPDATE OF s, d
\gset

-- A live observation supplies the local assignment metadata required by the
-- fixture table. A distinct digest marks values generated by this script.
SELECT agent_id AS fixture_agent, lease_id AS fixture_lease,
       session_generation AS fixture_session, configuration_revision AS fixture_config
FROM public.almanac_sli_observations
WHERE sli_id = :'fixture_id' AND measurement_revision = :'fixture_revision'
  AND outcome = 'observed'
ORDER BY interval_start DESC LIMIT 1
\gset

WITH bounds AS (
  SELECT make_interval(secs => :'fixture_cadence') AS cadence,
         date_bin(make_interval(secs => :'fixture_cadence'),
                  transaction_timestamp() - make_interval(secs => :'fixture_delay'),
                  '1970-01-01 00:00:00+00') - make_interval(secs => :'fixture_cadence') AS until
), requested AS (
  SELECT cadence, until, until - make_interval(days => :'days') AS since FROM bounds
), aligned AS (
  SELECT cadence, until, since,
         greatest(since, :'fixture_valid_from'::timestamptz) AS valid_since
  FROM requested
), eligible AS (
  SELECT cadence, until, since,
         date_bin(cadence, valid_since + cadence - interval '1 microsecond',
                  '1970-01-01 00:00:00+00') AS start_at
  FROM aligned
)
SELECT cadence AS fixture_step, since AS requested_start,
       least(start_at, until) AS eligible_start, until AS fixture_end
FROM eligible
\gset

-- Live maintenance only prepares partitions near the live replay window.
SELECT format('CREATE TABLE IF NOT EXISTS public.%I PARTITION OF public.almanac_sli_observations FOR VALUES FROM (%L) TO (%L)',
              'almanac_sli_observations_' || to_char(month, 'YYYYMM'), month, month + interval '1 month')
FROM generate_series(date_trunc('month', :'eligible_start'::timestamptz),
                     :'fixture_end'::timestamptz - interval '1 microsecond',
                     interval '1 month') AS month
WHERE :'eligible_start'::timestamptz < :'fixture_end'::timestamptz
  AND to_regclass('public.almanac_sli_observations_' || to_char(month, 'YYYYMM')) IS NULL
\gexec

WITH inserted AS (
  INSERT INTO public.almanac_sli_observations
    (sli_id, measurement_revision, interval_start, outcome, good_count, total_count,
     result_digest, execution_id, delivery_id, agent_id, session_generation,
     configuration_revision, lease_id, agent_created_at, recorded_at)
  SELECT :'fixture_id', :'fixture_revision', point, 'observed', 99, 100,
         sha256(convert_to('almanac local demo fixture', 'UTF8')),
         gen_random_uuid(), gen_random_uuid(), :'fixture_agent', :'fixture_session',
         :'fixture_config', :'fixture_lease', transaction_timestamp(), transaction_timestamp()
  FROM generate_series(:'eligible_start'::timestamptz,
                       :'fixture_end'::timestamptz - :'fixture_step'::interval,
                       :'fixture_step'::interval) AS point
  ON CONFLICT (sli_id, measurement_revision, interval_start) DO NOTHING
  RETURNING 1
)
SELECT :'requested_start' AS requested_start, :'eligible_start' AS eligible_start,
       :'fixture_end' AS end_at, count(*) AS intervals_inserted
FROM inserted;
