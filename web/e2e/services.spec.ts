import {expect,test} from '@playwright/test';
import {api,expectOk,unique} from './support/api.ts';

test('services persist metadata and dependencies, retain UUIDs on rename, and protect references',async({page},testInfo)=>{
 const providerName=unique('Payments'),display=unique('Checkout');
 const provider=await expectOk(api(page,'POST','/api/v1/services',{name:unique('payments'),display_name:providerName,owner:'Commerce'}));
 const started=performance.now();
 await page.goto('/services');await expect(page.locator('.services-table tbody tr').first()).toBeVisible();
 const listMs=performance.now()-started;expect(listMs).toBeLessThan(1000);
 await page.getByRole('link',{name:'New service',exact:true}).click();
 await page.getByLabel('Display name',{exact:true}).fill(display);
 await page.getByLabel(/^Description/).fill('Accepts and processes customer orders.');
 await page.getByRole('textbox',{name:/^Owner/}).fill('Store experience');
 await page.getByLabel(/^Contact/).fill('store@example.test');
 await page.getByRole('textbox',{name:'Labels',exact:true}).fill('team:store');await page.getByRole('textbox',{name:'Labels',exact:true}).press('Enter');
 await page.getByRole('textbox',{name:'Labels',exact:true}).fill('env:production');await page.getByRole('textbox',{name:'Labels',exact:true}).press('Enter');
 await page.getByLabel('Name',{exact:true}).fill('Runbook');await page.getByLabel('URL',{exact:true}).fill('https://docs.example.test/runbook');await page.getByLabel('URL',{exact:true}).press('Enter');
 await page.getByRole('combobox',{name:'Search dependencies'}).fill(providerName);
 await page.getByRole('option',{name:new RegExp(providerName)}).click();
 await expect(page.getByRole('button',{name:`Remove dependency ${providerName}`})).toBeVisible();
 await page.getByRole('button',{name:'Create service',exact:true}).click();
 await expect(page.getByRole('heading',{level:1,name:display,exact:true})).toBeVisible();
 const serviceID=new URL(page.url()).pathname.split('/').at(-1)!;
 await page.reload();await expect(page.getByRole('heading',{level:1,name:display,exact:true})).toBeVisible();
 await expect(page.getByRole('region',{name:'Service information'})).toContainText('team');
 await expect(page.getByRole('link',{name:'Runbook',exact:true})).toHaveAttribute('href','https://docs.example.test/runbook');
 const saved=await expectOk(api(page,'GET',`/api/v1/services/${serviceID}`));
 expect(saved.body.owner).toBe('Store experience');expect(saved.body.labels).toEqual({team:['store'],env:['production']});expect(saved.body.dependencies).toEqual([provider.body.id]);
 await page.getByRole('link',{name:'Edit service',exact:true}).click();
 await page.getByLabel('Display name',{exact:true}).fill(display+' renamed');
 await page.getByLabel('Identifier',{exact:true}).fill(unique('orders'));
 await page.getByRole('button',{name:'Save changes',exact:true}).click();
 await expect(page.getByRole('heading',{level:1,name:display+' renamed',exact:true})).toBeVisible();
 await expect(page).toHaveURL(new RegExp(serviceID+'$'));
 await page.getByRole('link',{name:new RegExp('Open '+providerName)}).click();
 await expect(page.getByRole('heading',{level:1,name:providerName,exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Delete service…',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'This service is still in use'})).toContainText(display+' renamed');
 await page.getByRole('button',{name:'Close',exact:true}).last().click();
 await page.goto(`/services/${serviceID}`);
 await page.getByRole('link',{name:'Create SLO',exact:true}).click();
 await expect(page).toHaveURL(new RegExp('service_id='+serviceID));
 await expect(page.getByText('Create an SLI before creating an objective.',{exact:true}).or(page.getByText(display+' renamed',{exact:true}))).toBeVisible();
 await page.goto('/services');
 await page.getByRole('link',{name:'Graph',exact:true}).click();
 await page.getByRole('combobox',{name:'Find a service'}).selectOption(serviceID);
 await expect(page.locator('.map-node.selected')).toHaveAttribute('data-id',serviceID);
 await expect(page.locator('.map-node.selected')).toHaveAttribute('data-slo-state','no_slos');
 await page.locator('.map-node').filter({hasText:providerName}).focus();await page.keyboard.press('Enter');
 await expect(page.locator('.map-node.selected')).toHaveAttribute('data-id',provider.body.id);
 await expect(page.locator('.graph-details')).toContainText(providerName);
 await page.goto(`/services/${serviceID}`);
 const detailStarted=performance.now();await page.reload();await expect(page.locator('.dependency-node')).toBeVisible();
 const detailMs=performance.now()-detailStarted;expect(detailMs).toBeLessThan(1000);
 await page.getByRole('button',{name:'Delete service…',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Delete service',exact:true}).click();
 await expect(page).toHaveURL(/\/services$/);
 expect((await api(page,'GET',`/api/v1/services/${serviceID}`)).status).toBe(404);
 await page.goto(`/services/${provider.body.id}`);
 await expect(page.getByText('No dependencies recorded.',{exact:true})).toBeVisible();
 await testInfo.attach('catalog first visit and detail timings',{body:JSON.stringify({fixture:'isolated HTTP/PostgreSQL, created services',listMs,detailMs}),contentType:'application/json'});
});

test('a Viewer can inspect the catalog but cannot mutate services through the API',async({page,browser})=>{
 const service=await expectOk(api(page,'POST','/api/v1/services',{name:unique('viewer-service'),display_name:unique('Viewer service')}));
 const email=unique('catalog-viewer')+'@example.test',password='A private service catalog viewer password 83';
 const account=await expectOk(api(page,'POST','/api/v1/users',{full_name:'Catalog Viewer',email,role:'viewer'}));
 const context=await browser.newContext({ignoreHTTPSErrors:true,storageState:{cookies:[],origins:[]}});
 try{
  const viewer=await context.newPage();await viewer.goto(account.body.link);
  await viewer.getByLabel('Password',{exact:true}).fill(password);await viewer.getByLabel('Confirm password',{exact:true}).fill(password);
  await viewer.getByRole('button',{name:'Set password',exact:true}).click();
  await viewer.getByRole('link',{name:'Continue to sign in',exact:true}).click();
  await viewer.getByLabel('Login',{exact:true}).fill(email);await viewer.getByLabel('Password',{exact:true}).fill(password);await viewer.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(viewer.getByRole('heading',{name:'Agents',exact:true})).toBeVisible();
  await viewer.goto('/services');await expect(viewer.locator('.services-table tbody tr').first()).toBeVisible();
  await expect(viewer.getByRole('link',{name:'New service',exact:true})).toHaveCount(0);
  await viewer.goto('/services/'+service.body.id);await expect(viewer.getByRole('heading',{name:service.body.display_name,exact:true})).toBeVisible();
  await expect(viewer.getByRole('link',{name:'Edit service',exact:true})).toHaveCount(0);await expect(viewer.getByRole('button',{name:'Delete service…',exact:true})).toHaveCount(0);
  expect((await api(viewer,'PATCH','/api/v1/services/'+service.body.id,{display_name:'Denied'},{'If-Match':service.etag!})).status).toBe(403);
  expect((await api(viewer,'DELETE','/api/v1/services/'+service.body.id,undefined,{'If-Match':service.etag!})).status).toBe(403);
  expect((await api(viewer,'POST','/api/v1/services',{name:unique('denied'),display_name:'Denied'})).status).toBe(403);
 }finally{await context.close();}
});
