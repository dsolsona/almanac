-- Unwired immutable physical start-hour populations. No queue or runtime defaults.
CREATE TABLE public.almanac_slo_maintenance_hours (
 slo_id uuid NOT NULL,
 definition_revision bigint NOT NULL CHECK(definition_revision>0),
 measurement_revision bigint NOT NULL CHECK(measurement_revision>0),
 build_id uuid NOT NULL REFERENCES public.almanac_maintenance_builds(id),
 hour_start timestamptz NOT NULL,
 source_generation bigint NOT NULL CHECK(source_generation>=0),
 sli_id uuid NOT NULL,
 exclusion_revision bigint NOT NULL CHECK(exclusion_revision>=0),
 prepared_at timestamptz NOT NULL,
 eligible_good numeric NOT NULL CHECK(eligible_good>=0),
 eligible_total numeric NOT NULL CHECK(eligible_total>=eligible_good),
 eligible_expected bigint NOT NULL CHECK(eligible_expected BETWEEN 0 AND 3600),
 eligible_observed bigint NOT NULL CHECK(eligible_observed BETWEEN 0 AND 3600),
 eligible_known_empty bigint NOT NULL CHECK(eligible_known_empty BETWEEN 0 AND 3600),
 eligible_zero_traffic bigint NOT NULL CHECK(eligible_zero_traffic BETWEEN 0 AND 3600),
 eligible_first_observation timestamptz,
 eligible_last_observation timestamptz,
 eligible_latest_receipt timestamptz,
 excluded_good numeric NOT NULL CHECK(excluded_good>=0),
 excluded_total numeric NOT NULL CHECK(excluded_total>=excluded_good),
 excluded_expected bigint NOT NULL CHECK(excluded_expected BETWEEN 0 AND 3600),
 excluded_observed bigint NOT NULL CHECK(excluded_observed BETWEEN 0 AND 3600),
 excluded_known_empty bigint NOT NULL CHECK(excluded_known_empty BETWEEN 0 AND 3600),
 excluded_zero_traffic bigint NOT NULL CHECK(excluded_zero_traffic BETWEEN 0 AND 3600),
 excluded_first_observation timestamptz,
 excluded_last_observation timestamptz,
 excluded_latest_receipt timestamptz,
 CHECK(eligible_observed+eligible_known_empty<=eligible_expected AND eligible_zero_traffic<=eligible_observed),
 CHECK((eligible_observed=0 AND eligible_first_observation IS NULL AND eligible_last_observation IS NULL AND eligible_good=0 AND eligible_total=0) OR (eligible_observed>0 AND eligible_first_observation IS NOT NULL AND eligible_last_observation IS NOT NULL AND eligible_first_observation<eligible_last_observation)),
 CHECK((eligible_observed+eligible_known_empty=0)=(eligible_latest_receipt IS NULL)),
 CHECK(excluded_observed+excluded_known_empty<=excluded_expected AND excluded_zero_traffic<=excluded_observed),
 CHECK((excluded_observed=0 AND excluded_first_observation IS NULL AND excluded_last_observation IS NULL AND excluded_good=0 AND excluded_total=0) OR (excluded_observed>0 AND excluded_first_observation IS NOT NULL AND excluded_last_observation IS NOT NULL AND excluded_first_observation<excluded_last_observation)),
 CHECK((excluded_observed+excluded_known_empty=0)=(excluded_latest_receipt IS NULL)),
 CHECK(isfinite(hour_start) AND hour_start=date_trunc('hour',hour_start AT TIME ZONE 'UTC') AT TIME ZONE 'UTC'),
 CHECK(isfinite(prepared_at)),
 CHECK(eligible_expected+excluded_expected<=3600),
 PRIMARY KEY(slo_id,definition_revision,measurement_revision,build_id,hour_start,source_generation),
 FOREIGN KEY(slo_id,definition_revision) REFERENCES public.almanac_slo_definitions(slo_id,revision),
 FOREIGN KEY(sli_id,measurement_revision) REFERENCES public.almanac_sli_measurements(sli_id,revision)
);
CREATE TRIGGER almanac_maintenance_hour_immutable BEFORE UPDATE ON public.almanac_slo_maintenance_hours FOR EACH ROW EXECUTE FUNCTION public.almanac_immutable_maintenance_revision();
